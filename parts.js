// ---------- главная функция ----------
// Принимает английское название из модели, возвращает { ru, la, desc, schematic }
export function getPartInfo(englishName) {
  const name = englishName.toLowerCase();

  if (PARTS[name]) return { ...PARTS[name], schematic: false };

  // Фаланги: «Distal phalanx of right index finger»
  let m = name.match(/^(proximal|middle|distal) phalanx of right (.+)$/);
  if (m && FINGERS[m[2]]) {
    const ph = PHALANGES[m[1]];
    const f = FINGERS[m[2]];
    return { ru: `${ph.ru} ${f.ru}`, la: `${ph.la} ${f.la}`, desc: ph.desc, schematic: false };
  }

  // Пястные кости: «Right first metacarpal bone»
  m = name.match(/^right (first|second|third|fourth|fifth) metacarpal bone$/);
  if (m) {
    const n = ORDINALS[m[1]];
    return {
      ru: `${n} пястная кость (${METACARPAL_FINGER[n]})`,
      la: `Os metacarpi ${n}`,
      desc: 'Одна из пяти пястных костей, которые образуют скелет ладони. Основанием соединяется с костями запястья, головкой — с проксимальной фалангой. ' + METACARPAL_EXTRA[n],
      schematic: false,
    };
  }

  // Схематичные боковые связки: «Radial collateral ligament of proximal interphalangeal joint of right index finger»
  m = name.match(/^(radial|ulnar) collateral ligament of (.+) joint of right (.+)$/);
  if (m && JOINTS[m[2]] && FINGERS[m[3]]) {
    const side = m[1] === 'radial' ? 'Лучевая' : 'Локтевая';
    const j = JOINTS[m[2]];
    const f = FINGERS[m[3]];
    let desc = 'Боковые (коллатеральные) связки укрепляют сустав с двух сторон и не дают пальцу сгибаться вбок. '
      + (m[1] === 'radial' ? 'Эта лежит со стороны большого пальца.' : 'Эта лежит со стороны мизинца.');
    if (m[3] === 'thumb' && m[2] === 'metacarpophalangeal' && m[1] === 'ulnar') {
      desc += ' Её разрыв часто случается при падении с лыжной палкой в руке («палец лыжника»).';
    }
    return {
      ru: `${side} коллатеральная связка ${j.ru} ${f.ru}`,
      la: `Lig. collaterale ${j.la} ${f.la}`,
      desc,
      schematic: true,
    };
  }

  // На всякий случай: если части нет в справочнике, показываем английское название
  return { ru: englishName, la: '', desc: 'Описание пока не добавлено.', schematic: false };
}
